#!/usr/bin/env python3
"""Render Sancai human interaction cards from the process graph.

Cards are generated by the harness, not narrated by the model. They always
show where the run is in the three-layer flow, what happened, why a human is
needed, the impact, and the available choices.

usage:
  sancai_card.py current --run R [--json]
  sancai_card.py intent --run R [--json]
  sancai_card.py approve --run R --esc ESC-001 [--json]
  sancai_card.py out-of-scope --run R --esc ESC-001 [--json]
  sancai_card.py ambiguous --run R --esc ESC-001 [--json]
  sancai_card.py accept --run R [--json]
  sancai_card.py blocked --run R --wo WO-001 [--json]
  sancai_card.py verify --run R --card-id CARD-... [--json]
  sancai_card.py status --run R [--json]

Actionable cards are persisted under .sancai/runs/<run>/L3-intent/decisions/cards/. The card is
bound to a canonical payload and printed with its card_id and card_code so a
human reply can be checked against the exact card they saw.
"""
import argparse
import json
import os

import sancai_paths as paths  # type: ignore
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import sancai_cards  # type: ignore
from sancai_graph import (  # type: ignore
    active_run,
    build_graph,
    find_node,
    find_root,
    open_escalations,
    position,
    run_dir,
    status_object,
    timeline_entries,
)
from sancai_state import intent_snapshot  # type: ignore


def _load_json(path, default):
    if not os.path.isfile(path):
        return default
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError):
        return default


def _escalation(graph, esc_id=None):
    if esc_id:
        for node in graph["nodes"]:
            if node.get("type") == "escalation" and node.get("id") == esc_id:
                return node
    escs = open_escalations(graph, blocking_only=True)
    return escs[0] if escs else None


def _what_from_escalation(esc):
    what = []
    if esc.get("what_i_tried"):
        what.append("Tried: " + "; ".join(str(x) for x in esc["what_i_tried"]))
    if esc.get("evidence"):
        what.append("Evidence: " + "; ".join(str(x) for x in esc["evidence"]))
    return what or ["No more detail provided."]


def detect_kind(graph):
    run = graph["nodes"][0]
    state = run.get("state")
    if state == "planning":
        return "intent", None, None

    esc = open_escalations(graph, blocking_only=True)
    if esc:
        first = esc[0]
        kind = {
            "irreversible": "approve",
            "out_of_scope": "out-of-scope",
            "spec_ambiguous": "ambiguous",
        }.get(first.get("esc_type"), "approve")
        return kind, first.get("id"), first.get("wo")

    if state == "executing":
        blocked = [
            n for n in graph["nodes"]
            if n.get("type") == "work_order" and n.get("state") == "blocked"
        ]
        if blocked:
            return "blocked", None, blocked[0]["id"]
        return "status", None, None

    if state == "reviewing":
        return "accept", None, None
    if state in ("accepted", "abandoned"):
        return "done", None, None
    return "status", None, None


def build_card(graph, kind, esc_id=None, wo_id=None):
    pos = position(graph)
    card = {
        "type": kind,
        "run": graph["run"],
        "state": pos["state"],
        "stage": pos["stage"],
        "layer": pos["layer"],
        "progress": pos["progress"],
        "next_action": pos["next_action"],
        "claim": pos["claim"],
        "trigger": pos["trigger"],
        "title": "",
        "what": [],
        "why": "",
        "impact": "",
        "options": [],
    }

    if kind == "intent":
        intent = graph.get("intent", {})
        card["title"] = "Confirm intent"
        card["what"] = [
            f"Goal: {intent.get('goal') or '—'}",
            f"Non-goals: {', '.join(intent.get('non_goals', [])) or '—'}",
            f"Acceptance: {intent.get('acceptance', 0)} criteria; Work Orders: {intent.get('work_orders', 0)}",
            f"Requirements: {', '.join(intent.get('requirements') or []) or '—'}"
            f" (revision {intent.get('revision') or '—'})",
        ]
        card["why"] = "Intent is the baseline for all later decisions; executing without confirmation amplifies rework."
        card["impact"] = "Approval moves to execution; changing the Intent requires re-signing."
        card["options"] = [
            {"n": 1, "label": "Start", "consequence": "Execute with the current Intent"},
            {"n": 2, "label": "Edit", "consequence": "Adjust goal / non-goals / acceptance, then start"},
            {"n": 3, "label": "Cancel", "consequence": "Abandon this request"},
        ]
        return card

    if kind in ("approve", "out-of-scope", "ambiguous"):
        esc = _escalation(graph, esc_id)
        if not esc:
            card["title"] = "No pending escalation"
            card["what"] = ["There is no open escalation."]
            card["why"] = "—"
            card["impact"] = "—"
            return card

        card["trigger"] = esc["id"]
        card["what"] = _what_from_escalation(esc)

        if kind == "approve":
            card["title"] = "Approve: irreversible action"
            card["why"] = "This action is irreversible and must be approved by a human; the agent cannot release it."
            card["impact"] = "Approval applies only to the current diff; the token expires if the diff changes."
            card["options"] = [
                {"n": 1, "label": "approve", "consequence": "Execute once; token expires if the diff changes"},
                {"n": 2, "label": "reject", "consequence": "Send back to the executor for a new plan"},
                {"n": 3, "label": "Show details", "consequence": "Show the raw operation and diff"},
                {"n": 4, "label": "Change the plan first", "consequence": "Do not approve; require a smaller action"},
            ]
        elif kind == "out-of-scope":
            card["title"] = "Decide: out of scope"
            card["why"] = "Execution exceeded the current WO's owned_files / requirement boundary."
            card["impact"] = "Expanding scope affects other WOs; splitting a new WO keeps boundaries clear."
            card["options"] = [
                {"n": 1, "label": "Expand scope", "consequence": "Update owned_files and continue"},
                {"n": 2, "label": "Split a new WO", "consequence": "Keep this WO in bounds and open another WO"},
                {"n": 3, "label": "Abandon", "consequence": "Stop the current WO"},
            ]
        else:
            card["title"] = "Clarify: requirement ambiguity"
            card["why"] = "The requirement is ambiguous; guessing causes rework."
            card["impact"] = "The choice changes the implementation direction."
            opts = esc.get("options") or []
            if opts:
                for i, opt in enumerate(opts, 1):
                    card["options"].append({
                        "n": i,
                        "label": str(opt),
                        "consequence": "Continue in this direction",
                    })
                card["options"].append({
                    "n": len(opts) + 1,
                    "label": "Add constraints",
                    "consequence": "Continue after the human adds constraints",
                })
            else:
                card["options"] = [
                    {"n": 1, "label": "Choose A", "consequence": "Continue with A"},
                    {"n": 2, "label": "Choose B", "consequence": "Continue with B"},
                    {"n": 3, "label": "Add constraints", "consequence": "Continue after the human adds constraints"},
                ]
        if kind in ("approve", "out-of-scope") and esc.get("options"):
            for opt in esc["options"]:
                card["options"].append({
                    "n": len(card["options"]) + 1,
                    "label": str(opt),
                    "consequence": "Escalation suggestion; state the choice when approving or rejecting",
                })
        return card

    if kind == "accept":
        metrics = graph["metrics"]
        findings = sum(
            n.get("findings", 0)
            for n in graph["nodes"] if n.get("type") == "verdict"
        )
        gates = [n for n in graph["nodes"] if n.get("type") == "gate"]
        gate_text = ", ".join(f"{g['id']}={g.get('result')}" for g in gates) or "—"
        card["title"] = "Acceptance: outcome pending"
        selected = graph.get("intent", {}).get("requirements") or []
        coverage = []
        for req_id in selected:
            wos = [
                n["id"] for n in graph["nodes"]
                if n.get("type") == "work_order"
                and n.get("req") == req_id
                and n.get("state") in ("verified", "merged")
            ]
            coverage.append(f"{req_id}: {', '.join(wos) or 'uncovered'}")
        captured = graph.get("captured_todos") or []
        card["what"] = [
            f"{metrics['wo_verified']}/{metrics['wo_total']} Work Orders verified",
            f"Gate: {gate_text}",
            f"verifier findings：{findings}",
            f"Rework: {metrics['rework']} times; escalations: {metrics['escalations']}",
        ]
        if selected:
            card["what"].append("Requirement coverage: " + "; ".join(coverage))
        if captured:
            card["what"].append(
                "Out-of-scope captured: "
                + ", ".join(f"{item['id']} ({item.get('relation')})" for item in captured)
            )
        card["why"] = "Acceptance is a human decision, not the agent's self-assessment."
        card["impact"] = "Accepting ends the request; sending back re-enters execution."
        card["options"] = [
            {"n": 1, "label": "accept", "consequence": "End this request"},
            {"n": 2, "label": "Show evidence", "consequence": "Show gate / evidence / findings"},
            {"n": 3, "label": "Send back for changes", "consequence": "State the reason and return to execution"},
        ]
        return card

    if kind == "blocked":
        blocked = [
            n for n in graph["nodes"]
            if n.get("type") == "work_order" and n.get("state") == "blocked"
        ]
        wo = None
        if wo_id:
            wo = next((w for w in blocked if w["id"] == wo_id), None)
        wo = wo or (blocked[0] if blocked else None)
        card["title"] = "Handle: execution blocked"
        card["layer"] = "L3"
        if wo:
            card["trigger"] = wo["id"]
            gate = find_node(graph, "gate", wo=wo["id"])
            reasons = gate.get("reasons", []) if gate else []
            card["what"] = [
                f"{wo['id']} is blocked",
                "Reason: " + ("; ".join(reasons) if reasons else "see gate record"),
            ]
        else:
            card["what"] = ["No Work Order is blocked."]
        card["why"] = "The flow is paused and needs a human to unblock it."
        card["impact"] = "It cannot continue until unblocked."
        card["options"] = [
            {"n": 1, "label": "Unblock", "consequence": "Explain how to unblock and continue"},
            {"n": 2, "label": "Abandon", "consequence": "Stop the current WO"},
            {"n": 3, "label": "Show details", "consequence": "Show the blocking reason"},
        ]
        return card

    if kind == "done":
        card["title"] = "This request has ended"
        card["what"] = [
            f"State: {pos['state']}",
            f"Progress: {pos['progress']}",
        ]
        card["why"] = "—"
        card["impact"] = "—"
        return card

    card["title"] = "No action needed from you"
    card["what"] = [
        f"State: {pos['state']}",
        f"Progress: {pos['progress']}",
        f"Next: {pos['next_action']}",
    ]
    card["why"] = "There are no blocking items for you."
    card["impact"] = "—"
    return card


def _all_findings(root, run):
    findings = []
    vdir = paths.verdicts_dir(root, run)
    if not os.path.isdir(vdir):
        return findings
    for name in sorted(os.listdir(vdir)):
        if not name.endswith(".json"):
            continue
        verdict = _load_json(os.path.join(vdir, name), {})
        items = verdict.get("findings") if isinstance(verdict, dict) else None
        if isinstance(items, list):
            findings.extend(items)
    return findings


def _intent_payload(root, run):
    run_data = _load_json(paths.run_path(root, run), {})
    intent = _load_json(
        paths.intent_path(root, run, run_data), {}
    )
    return {
        "intent_sha": intent_snapshot(intent),
        "goal": intent.get("goal", ""),
        "acceptance_count": len(intent.get("acceptance", [])),
        "work_order_count": len(run_data.get("work_orders", {})),
        "alignment_status": (intent.get("alignment") or {}).get("status", "missing"),
    }


def _escalation_payload(esc):
    return {
        "esc": esc.get("id"),
        "wo": esc.get("wo"),
        "esc_type": esc.get("esc_type"),
        "status": esc.get("status"),
        "what_tried": esc.get("what_i_tried", []),
        "evidence": esc.get("evidence", []),
        "options": esc.get("options", []),
    }


def _accept_payload(root, run, graph):
    run_node = graph["nodes"][0]
    wos = {
        n["id"]: n.get("state")
        for n in graph["nodes"] if n.get("type") == "work_order"
    }
    gate_results = {
        n.get("wo"): n.get("result")
        for n in graph["nodes"] if n.get("type") == "gate"
    }
    findings = _all_findings(root, run)
    return {
        "run": run,
        "state": run_node.get("state") or "reviewing",
        "wos": wos,
        "gate_results": gate_results,
        "findings_hash": sancai_cards.findings_hash(findings),
        "findings_count": len(findings),
    }


def _blocked_payload(graph, wo_id=None):
    blocked = [
        n for n in graph["nodes"]
        if n.get("type") == "work_order" and n.get("state") == "blocked"
    ]
    if wo_id:
        wo = next((w for w in blocked if w["id"] == wo_id), None)
    else:
        wo = blocked[0] if blocked else None
    wo = wo or (blocked[0] if blocked else None)
    if not wo:
        return None
    gate = find_node(graph, "gate", wo=wo["id"])
    return {
        "wo": wo["id"],
        "state": "blocked",
        "reasons": gate.get("reasons", []) if gate else [],
    }


def card_payload(root, run, graph, kind, esc_id=None, wo_id=None):
    """Stable binding payload for an actionable card, or None if inapplicable."""
    if kind == "intent":
        return _intent_payload(root, run)
    if kind in ("approve", "out-of-scope", "ambiguous"):
        esc = _escalation(graph, esc_id)
        return _escalation_payload(esc) if esc else None
    if kind == "accept":
        return _accept_payload(root, run, graph)
    if kind == "blocked":
        return _blocked_payload(graph, wo_id)
    return None


FLOW_LANES = (
    ("L3 Intent", "L3", (
        "intent", "assess", "align", "H1 sign", "(H2 approve)", "H3 accept",
    )),
    ("L2 Harness", "L2", ("add-wo", "claim", "G0", "G3", "gate")),
    ("L1 Code", "L1", ("executor", "verifier")),
)


def _flow_active(card):
    """Return the lane token this decision sits on, from deterministic state."""
    kind = card.get("type")
    state = card.get("state")
    action = card.get("next_action")
    if kind == "intent":
        return {"L3": "H1 sign"}
    if kind in ("approve", "out-of-scope", "ambiguous"):
        return {"L3": "(H2 approve)"}
    if kind == "accept":
        return {"L3": "H3 accept"}
    if kind == "blocked":
        return {"L2": "gate"}
    if state == "planning":
        return {"L3": "H1 sign"}
    if state == "reviewing":
        return {"L3": "H3 accept"}
    if state == "executing":
        if action == "approve":
            return {"L3": "(H2 approve)"}
        if action == "wait":
            by = (card.get("claim") or {}).get("by", "")
            return {"L1": "verifier" if "verif" in by.lower() else "executor"}
        if action == "dispatch":
            return {"L2": "claim"}
        return {"L2": "gate"}
    if state == "accepted":
        return {"L3": "H3 accept"}
    return {}


def flow_context(card):
    """ASCII background flow with the current decision marked by ▶ … ◀."""
    active = _flow_active(card)
    lines = ["Flow context (▶ = this decision)"]
    for label, key, tokens in FLOW_LANES:
        rendered = [
            f"▶{token}◀" if token == active.get(key) else token
            for token in tokens
        ]
        lines.append(f"{label:<11}" + " ─ ".join(rendered))
    return lines


def render(card):
    lines = []
    lines.append(f"【{card['title']}】  {card['run']}")
    lines.append("─" * 60)
    lines.extend(flow_context(card))
    lines.append("")
    lines.append(f"Stage  {card['stage']}")
    lines.append(f"Layer  {card['layer']}")
    lines.append(f"Progress      {card['progress']}")
    lines.append(f"Trigger      {card['trigger'] or '—'}")
    lines.append("")
    lines.append("What happened")
    for item in card["what"]:
        lines.append(f"  - {item}")
    lines.append("")
    lines.append("Why you are needed")
    lines.append(f"  {card['why']}")
    lines.append("")
    lines.append("Impact")
    lines.append(f"  {card['impact']}")
    if card["options"]:
        lines.append("")
        lines.append("You can")
        for opt in card["options"]:
            lines.append(f"  {opt['n']}. {opt['label']} —— {opt['consequence']}")
    if card.get("card_id"):
        lines.append("")
        lines.append(
            f"Card  {card['card_id']}   Code  {card['card_code']}"
        )
        reply_verb = {
            "intent": "confirm",
            "approve": "approve",
            "out-of-scope": "approve",
            "ambiguous": "approve",
            "accept": "accept",
        }.get(card["type"], "confirm")
        lines.append(
            f"Reply example: {reply_verb} {card['card_id']} {card['card_code']}"
        )
    lines.append("─" * 60)
    return "\n".join(lines)


def cmd_progress_card(root, run, as_json):
    """Read-only progress card; it never authorizes anything."""
    status = status_object(root, run)
    if status is None:
        sys.exit(f"run not found: {run}")
    recent = timeline_entries(root, run, 5)
    if as_json:
        print(json.dumps({"status": status, "recent": recent}, ensure_ascii=False, indent=2))
        return 0
    line = "─" * 60
    print(line)
    print(f"  Sancai progress   {status['run']}")
    print(f"  state          : {status['state']}")
    print(f"  stage          : {status['stage']}")
    print(f"  layer          : {status['layer']}")
    flow_card = {
        "type": "status",
        "state": status["state"],
        "next_action": status["next_action"],
        "claim": status.get("claim"),
    }
    for flow_line in flow_context(flow_card):
        print(f"  {flow_line}")
    print(f"  progress       : {status['progress']}")
    print(f"  claim          : {(status.get('claim') or {}).get('wo') or '-'}")
    print(f"  next           : {status['next']['action']} — {status['next']['reason']}")
    print(f"  open esc       : {', '.join(status['open_escalations']) or '-'}")
    if recent:
        print("  recent events  :")
        for entry in recent:
            print(
                f"    {entry['time']}  {entry['event']:18s} "
                f"{entry['subject']:12s} {entry['from']}→{entry['to']}"
            )
    print("  This card is read-only. No action is required.")
    print(line)
    return 0


def cmd_verify(root, run, card_id, as_json):
    card = sancai_cards.load_card(root, run, card_id)
    problems = sancai_cards.verify_card(card)
    verification = {"ok": not problems, "problems": problems}
    if as_json:
        out = dict(card)
        out["verification"] = verification
        print(json.dumps(out, ensure_ascii=False, indent=2))
    else:
        print(f"Card  {card.get('card_id')}   Code  {card.get('card_code')}")
        print(f"run         : {card.get('run')}")
        print(f"kind        : {card.get('kind')}")
        print(f"tier        : {card.get('tier')}")
        print(f"created_at  : {card.get('created_at')}")
        print(f"used_at     : {card.get('used_at') or '—'}")
        print(f"card_hash   : {card.get('card_hash')}")
        print(f"mac         : {card.get('mac') or '—'}")
        print("payload     :")
        print(json.dumps(card.get("payload"), ensure_ascii=False, indent=2))
        print("verification:")
        print(f"  ok        : {verification['ok']}")
        for problem in problems:
            print(f"  problem   : {problem}")
    return 0 if verification["ok"] else 1


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)

    for name in (
        "current", "intent", "approve", "out-of-scope",
        "ambiguous", "accept", "blocked",
    ):
        p = sub.add_parser(name)
        p.add_argument("--run")
        p.add_argument("--esc")
        p.add_argument("--wo")
        p.add_argument(
            "--tier", choices=sorted(sancai_cards.DWELL_SECONDS), default="T2"
        )
        p.add_argument("--json", action="store_true")
        p.set_defaults(kind=name)

    p = sub.add_parser("verify")
    p.add_argument("--run")
    p.add_argument("--card-id", required=True)
    p.add_argument("--json", action="store_true")

    p = sub.add_parser("status")
    p.add_argument("--run")
    p.add_argument("--json", action="store_true")

    args = ap.parse_args()
    root = find_root()

    if args.cmd == "status":
        run = args.run or active_run(root)
        sys.exit(cmd_progress_card(root, run, args.json))

    if args.cmd == "verify":
        run = args.run or active_run(root)
        try:
            sys.exit(cmd_verify(root, run, args.card_id, args.json))
        except sancai_cards.CardError as exc:
            sys.exit(str(exc))

    run = args.run or active_run(root)
    graph = build_graph(root, run)

    kind = args.kind
    esc_id = args.esc
    wo_id = args.wo
    if kind == "current":
        kind, auto_esc, auto_wo = detect_kind(graph)
        esc_id = esc_id or auto_esc
        wo_id = wo_id or auto_wo

    if kind in ("status", "done"):
        sys.exit(cmd_progress_card(root, run, args.json))

    card = build_card(graph, kind, esc_id, wo_id)
    if kind in sancai_cards.CARD_KINDS:
        payload = card_payload(root, run, graph, kind, esc_id, wo_id)
        if payload is not None:
            saved = sancai_cards.make_card(
                root, run, kind, payload, card.get("options", []), tier=args.tier
            )
            for key in (
                "card_id", "card_code", "card_hash", "tier",
                "created_at", "used_at", "mac",
            ):
                card[key] = saved.get(key)
    if args.json:
        print(json.dumps(card, ensure_ascii=False, indent=2))
    else:
        print(render(card))


if __name__ == "__main__":
    main()
